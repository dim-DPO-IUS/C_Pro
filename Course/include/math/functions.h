/**
 * @file math/functions.h
 * @brief Целевые функции из условия задачи и их производные
 */

#ifndef MATH_FUNCTIONS_H
#define MATH_FUNCTIONS_H

#include "math/functions.h"
#include <math.h>

/*============================================================================*/
/*                            ЦЕЛЕВЫЕ ФУНКЦИИ                                 */
/*============================================================================*/

/**
 * @brief f1(x) = 0.6x + 3
 */
float f1(float x);

/**
 * @brief f2(x) = (x-2)³ - 1
 */
float f2(float x);

/**
 * @brief f3(x) = 3/x
 */
float f3(float x);

/*============================================================================*/
/*                            ПРОИЗВОДНЫЕ ФУНКЦИЙ                             */
/*============================================================================*/

/**
 * @brief Производная f1(x) = 0.6
 */
float df1(float x);

/**
 * @brief Производная f2(x) = 3(x-2)²
 */
float df2(float x);

/**
 * @brief Производная f3(x) = -3/x²
 */
float df3(float x);

/*============================================================================*/
/*                            ФУНКЦИИ РАЗНОСТИ                                */
/*============================================================================*/

/**
 * @brief f1(x) - f2(x)
 */
float diff_f1_f2(float x);

/**
 * @brief f1(x) - f3(x)
 */
float diff_f1_f3(float x);

/**
 * @brief f2(x) - f3(x)
 */
float diff_f2_f3(float x);

/*============================================================================*/
/*                            ПРОИЗВОДНЫЕ РАЗНОСТЕЙ                           */
/*============================================================================*/

/**
 * @brief Производная (f1 - f2)'(x) = 0.6 - 3(x-2)²
 */
float diff_df1_df2(float x);

/**
 * @brief Производная (f1 - f3)'(x) = 0.6 + 3/x²
 */
float diff_df1_df3(float x);

/**
 * @brief Производная (f2 - f3)'(x) = 3(x-2)² + 3/x²
 */
float diff_df2_df3(float x);

#endif /* MATH_FUNCTIONS_H */