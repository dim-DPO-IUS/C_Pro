/**
 * @struct Interval
 * @brief Структура для хранения интервала, содержащего корень
 * 
 * Используется при локализации корней: после разбиения области поиска
 * на мелкие интервалы, те из них, на которых функция меняет знак,
 * сохраняются в виде таких структур для последующего уточнения.
 */
typedef struct {
    float left;   /**< Левая граница интервала */
    float right;  /**< Правая граница интервала */
} Interval;

/**
 * @struct Point
 * @brief Структура для хранения точки пересечения функций
 * 
 * Содержит полную информацию о найденной точке пересечения:
 * координаты, какие функции пересекаются, и сколько итераций
 * потребовалось для её нахождения.
 */
typedef struct {
    float x;           /**< Абсцисса точки пересечения */
    float y;           /**< Ордината точки пересечения */
    int pair_type;     /**< Тип пересекающихся функций: 1=f1f2, 2=f1f3, 3=f2f3 */
    int iterations;    /**< Количество итераций, затраченных на поиск */
} Point;

/**
 * @struct Config
 * @brief Структура конфигурации программы
 * 
 * Содержит все настройки программы, полученные из командной строки
 * или установленные по умолчанию. Передаётся между модулями для
 * обеспечения единообразного поведения.
 */
typedef struct {
    // Параметры точности
    float eps_root;        /**< Точность поиска корней */
    float eps_integral;    /**< Точность интегрирования */
    
    // Методы
    int root_method;       /**< Метод поиска корней: 0-деление, 1-хорды, 2-касательные, 3-комбинированный */
    int integral_method;   /**< Метод интегрирования: 0-прямоугольники, 1-трапеции, 2-Симпсон */
    
    // Флаги режимов работы
    int test_mode;         /**< Флаг режима тестирования (-t) */
    int visualize;         /**< Флаг визуализации (-v) */
    
    // Флаги для опций вывода
    int flag_abscissas;    /**< Флаг вывода только абсцисс (-a) */
    int flag_points;       /**< Флаг подробного вывода точек (-p) */
    int flag_iterations;   /**< Флаг вывода итераций (-i) */
    int flag_log;          /**< Флаг логирования в файл (--log) */
} Config;

