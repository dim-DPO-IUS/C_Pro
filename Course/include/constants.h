/**
 * @enum FunctionType
 * @brief Типы функций для идентификации в геометрических операциях
 * 
 * Используется для указания, какая функция является верхней или нижней
 * границей сегмента фигуры. Значения выбраны так, чтобы можно было
 * использовать в битовых масках при необходимости.
 */
typedef enum {
    FUNC_NONE = 0,  /**< Функция не определена */
    FUNC_F1 = 1,    /**< Первая функция: f1(x) = 0.6x + 3 */
    FUNC_F2 = 2,    /**< Вторая функция: f2(x) = (x-2)³ - 1 */
    FUNC_F3 = 3     /**< Третья функция: f3(x) = 3/x */
} FunctionType;

