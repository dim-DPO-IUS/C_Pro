/**
 * @def EPS_ROOT_DEFAULT
 * @brief Точность поиска корней по умолчанию
 * 
 * Используется, если пользователь не указал свою точность через опции
 * командной строки. Определяет допустимую погрешность при нахождении корней.
 * Значение: 1e-6f (0.000001)
 */
#define EPS_ROOT_DEFAULT 1e-6f

/**
 * @def EPS_INTEGRAL_DEFAULT
 * @brief Точность интегрирования по умолчанию
 * 
 * Используется, если пользователь не указал свою точность через опции
 * командной строки. Определяет допустимую погрешность при вычислении
 * определённых интегралов.
 * Значение: 1e-4f (0.0001)
 */
#define EPS_INTEGRAL_DEFAULT 1e-4f

/**
 * @def EPS_COMPARE_FACTOR
 * @brief Множитель для сравнения значений функций
 * 
 * Используется при проверке найденных корней: значение функции в точке
 * считается нулевым, если его модуль меньше eps * EPS_COMPARE_FACTOR.
 * Позволяет учесть накопленную погрешность вычислений.
 * Значение: 100.0f
 */
#define EPS_COMPARE_FACTOR 100.0f

/**
 * @def EPS_TANGENT_FACTOR
 * @brief Множитель для проверки зацикливания в методе касательных
 * 
 * Используется для обнаружения ситуации, когда метод касательных "застревает"
 * и перестаёт сходиться. Если изменение x меньше eps * EPS_TANGENT_FACTOR,
 * но значение функции ещё велико, метод считается расходящимся.
 * Значение: 0.01f
 */
#define EPS_TANGENT_FACTOR 0.01f

