/**
 * @file math/functions.c
 * @brief Реализация целевых функций и их производных
 */

#include "math/functions.h"
#include <math.h>

/*============================================================================*/
/*                            ЦЕЛЕВЫЕ ФУНКЦИИ                                 */
/*============================================================================*/

float f1(float x) {
    return 0.6f * x + 3.0f;
}

float f2(float x) {
    return powf(x - 2.0f, 3) - 1.0f;
}

float f3(float x) {
    if (x == 0) return NAN;
    return 3.0f / x;
}

/*============================================================================*/
/*                            ПРОИЗВОДНЫЕ ФУНКЦИЙ                             */
/*============================================================================*/

float df1(float x) {
    (void)x;
    return 0.6f;
}

float df2(float x) {
    return 3.0f * powf(x - 2.0f, 2);
}

float df3(float x) {
    return -3.0f / (x * x);
}

/*============================================================================*/
/*                            ФУНКЦИИ РАЗНОСТИ                                */
/*============================================================================*/

float diff_f1_f2(float x) {
    return f1(x) - f2(x);
}

float diff_f1_f3(float x) {
    return f1(x) - f3(x);
}

float diff_f2_f3(float x) {
    return f2(x) - f3(x);
}

/*============================================================================*/
/*                            ПРОИЗВОДНЫЕ РАЗНОСТЕЙ                           */
/*============================================================================*/

float diff_df1_df2(float x) {
    return df1(x) - df2(x);
}

float diff_df1_df3(float x) {
    return df1(x) - df3(x);
}

float diff_df2_df3(float x) {
    return df2(x) - df3(x);
}