int main()
{
    /*=======================================================================*/
    /* ---------- ИНИЦИАЛИЗАЦИЯ ПЕРЕМЕННЫХ СЕРВЕРА-------------------------- */
    /*=======================================================================*/
    /*
       1. client/server - два дескриптора.
       Эти две перемнные хранят значение сокетов, которые вернула система при подключении.

       2. portNum - нужен для хранения номера порта, на котором происходит соединение.

       3. isExit - булевая переменная, признак завершения программы.

       4. buffer[] - Сервер считывает сообщение из сокет соединения в буффер обмена для приема/отправки данных к/от сервера.
    */

    int server;//дескриптор сервера
    int client;//дескриптор клиента 
    int portNum = 1502;//номера порта, на котором происходит соединение (0 до 65535)
    bool isExit = false;//булевая переменная, признак завершения программы.
    int bufsize = 1024;//размер буффера
    char buffer[bufsize]; //буффер обмена для приема/отправки данных к/от сервера

    /*
       5. A sockaddr_in - структура, содержащая интернет адрес, с которым будет установлено соединение.
       Эта структура уже определена в netinet/in.h, поэтому нет необходимости заново ее задавать.
        DEFINITION:
        struct sockaddr_in
        {
          short   sin_family;
          u_short sin_port;
          struct  in_addr sin_addr;
          char    sin_zero[8];
        };

        6. serv_addr будет содержать адрес сервера

        7. socklen_t - длиной по крайней мере 32 бита
    */

    struct sockaddr_in server_addr;
    socklen_t size;

    /*=======================================================================*/
    /* ---------- УСТАНОВКА СОКЕТ СОЕДИНЕНИЯ --------------------------------*/
    /*=======================================================================*/

    /* --------------- socket() функция ------------------*/

     /*
        Socket() функция создает новый сокет.
        На вход получает 3 аргумента,
            a. AF_INET: доменный адрес сокета.
            b. SOCK_STREAM: тип сокета. Потоковый сокет, в котором сообщение
            читается последовательным потоком(TCP).
            c. Третий это аргумент протокола: всегда должен быть 0. Операционная система выберет самый подходящий протокол.

            Функция возвращает файл-дескриптор целое число - соединение, которое используется для всех ссылок
            на этот сокет. Если произошла ошибка соединения, то возвращается -1.
    */

    server = socket(AF_INET, SOCK_STREAM, 0); // Создание сервер-сокета
    printf("SERVER\n");

    if (server < 0)
    {
        printf("Error establishing socket...\n");
        exit(1);
    }

    printf("=> Socket server has been created...\n");

    /*=======================================================================*/
    /* ---------- ИНИЦИАЛИЗАЦИЯ serv_addr ---------------------------------- */
    /*=======================================================================*/
    /*
        Переменная serv_addr - структура sockaddr_in.

        sin_family содержит код для адресной семьи. Всегда должна быть установлена AF_INET.

        htons() функция переводит номер порта из последовательности байтов компьютера в номер порта для работы с сетью.

        INADDR_ANY содержит IP-адрес хоста. Для сервера - это IP-адрес компьютера, на котором работает сервер.
    */

    server_addr.sin_family = AF_INET;
    server_addr.sin_port = htons(portNum);
    server_addr.sin_addr.s_addr = htons(INADDR_ANY);

    /*=======================================================================*/
    /* ---------- ПРИВЯЗКА СОКЕТА ------------------------------------------ */
    /*=======================================================================*/
    /* ---------------- bind() ---------------- */
    /*
        bind() функция привязывает сокет к адресу, то есть в нашем случае
        к адресу сервера и номеру порта, на котором сервер будет работать.
        Для этого нужны три аргумента:
            a. файл дескриптор сокета,
            b. указатель на структуру типа sockaddr (должен указывать на правильный тип)
            c. и размер структуры типа server_addr
    */

    if ((bind(server, (struct sockaddr*)&server_addr, sizeof(server_addr))) < 0)
    {
        printf("=> Error binding connection, the socket has already been established...\n");
        return -1;
    }

    size = sizeof(server_addr);
    printf("=> Looking for clients...\n"); // Ждем клиента

    /*=======================================================================*/
    /* ------------- ПРОСЛУШИВАНИЕ СОКЕТА ---------------------------------- */
    /*=======================================================================*/

    /* ---------------- listen() ---------------- */

    /*
        Функция listen позволяет прослушивать сокет для подключения.

        Программа будет ждать, пока не произойдет подключения клиента.
        Программа будет в состоянии простоя, если подключений не обнаружится.

        Первый аргумент - это файл дескриптор сокета, второй - количество клиентов,
        то есть количество подключений, которое сервер может обработать, пока процесс
        обрабатывает определенное подключение. Максимальное число клиентов во многих
        системах равняется 5.
    */

    listen(server, 1);

    /*=======================================================================*/
    /* ------------- ПОДКЛЮЧЕНИЕ КЛИЕНТОВ  --------------------------------- */
    /*=======================================================================*/

    /* ----------------- accept() ------------------- */

    /*
        Система accept() вызывает процесс блокировки пока клиент подключается к серверу.
        К тому же, она пробуждает процесс, когда подключение с клиентом было успешно установлено.
        Она возвращает новый файл дескриптор, и вся связь по этому подключению должна
        осуществляться, используя новый файл дескриптор. Второй аргумент - указатель на
        адрес клиента, третий - размер структуры.
    */

    int clientCount = 1;
    client = accept(server, (struct sockaddr*)&server_addr, &size);

    // первая проверка действительности подключения
    if (client < 0)
        printf("=> Error on accepting...");


    /*=======================================================================*/
    /* ------------- ОСНОВНОЙ ЦИКЛ  ---------------------------------------- */
    /*=======================================================================*/
    /*
        Мы перейдем в этот момент только после того, как клиент успешно подключится к
        нашему серверу.

        Произойдет чтение сокета. Заметим, что read() будет блокировать до момента наличия чего-то
        для чтения, то есть пока клиент не совершит send(). Чтение будет происходить до достижения
        1024 символов в пакете.

        Как только соединение будет установлено, оба конца связи могут писать и читать соединение.
        Все, написанное клиентом, будет прочитано сервером, а все, написанное сервером, будет
        прочитано клиентом.
        Чтение будет происходить maximum 1024 символов в пакете
    */

    //Основной цикл
    while (client > 0)
    {
        /*===================================================================*/
        /* ---------------- ОЖИДАНИЕ КЛИЕНТА ------------------------------- */
        /*===================================================================*/
        printf("=> Connected with the client %d, you are good to go...\n", clientCount);
        printf("\n=> Enter # to end the connection\n");

        // Отправка приветственного сообщения с байт-стаффингом
        send_encoded_string(client, "=> Server connected...\n");

        /*===================================================================*/
        /* ---------------- ПРИЕМ СООБЩЕНИЙ ОТ КЛИЕНТА --------------------- */
        /*===================================================================*/
        /*
            После соединения с клиентом ждем от него сообщение и вычитываем его
            значение с декодированием. Если приходит #, завершаем программу.
        */
        do
        {
            printf("Client: ");
            if (!receive_and_display(client, &isExit))
            {
                printf("=> Error receiving message or connection closed\n");
                isExit = true;
                break;
            }

            /*===============================================================*/
            /* ---------------- ОТВЕТ СЕРВЕРА ------------------------------ */
            /*===============================================================*/
            /*
                Считываем ответное сообщение сервера и отправляем его клиенту
                с байт-стаффингом. Если приходит #, завершаем программу.
            */
            printf("\nServer: ");
            if (!input_and_send_encoded(client, &isExit))
            {
                printf("=> Error sending message\n");
                isExit = true;
                break;
            }

        } while (!isExit);

        /*===================================================================*/
        /* ---------------- ЗАВЕРШЕНИЕ СОЕДИНЕНИЯ -------------------------- */
        /*===================================================================*/

        /* ----------------- close() --------------- */

        /*
            Как только сервер нажмет # для завершения программы, основной цикл
            завершится и закроет клиентский, а затем и серверный сокет соединения
            функцией close().
            Полностью завершаем работу программы.
        */

        // inet_ntoa переводит данные пакета в IP-адрес, который был взят у клиента  
        printf("\n\n=> Connection terminated with IP %s\n", inet_ntoa(server_addr.sin_addr));
        close(client);
        close(server);
        printf("\nGoodbye...");
        isExit = false;
        //~ exit(1);
        return 0;

    }

    return 0;
}
