int main()
{
    /*=======================================================================*/
    /* ---------- ИНИЦИАЛИЗАЦИЯ ПЕРЕМЕННЫХ КЛИЕНТА-------------------------- */
    /*=======================================================================*/
    /*
       1. client - файл-дескриптор, хранящий значение сокета, которые вернула
       система при подключении к серверу.

       2. portNum нужен для хранения номера порта, на котором происходит
       соединение.

       3. isExit - булевая переменная, признак завершения программы.

       4. buffer[] - Клиент считывает сообщение из сокета соединения в буффер
       обмена для приема/отправки данных к/от сервера
    */

    int client; // дескриптор клиента
    int portNum = 1502; // номер порта один для сервера и клиента!
    bool isExit = false; // булевая переменная, признак завершения программы.
    int bufsize = 1024; // размер буффера
    char buffer[bufsize]; // буффер обмена для приема/отправки данных к/от сервера

    /*
        5. sockaddr_in - структура, содержащая интернет адрес, с которым будет
       установлено соединение. Эта структура уже определена в netinet/in.h,
       поэтому нет необходимости заново ее задавать. DEFINITION: struct
       sockaddr_in
        {
          short   sin_family;
          u_short sin_port;
          struct  in_addr sin_addr;
          char    sin_zero[8];
        };

        6. serv_addr будет содержать адрес сервера
    */

    struct sockaddr_in server_addr;
    char* ip = "127.0.0.1"; // будем делать loopback

    /*=======================================================================*/
    /* ---------- УСТАНОВКА СОКЕТ СОЕДИНЕНИЯ --------------------------------*/
    /*=======================================================================*/

    /* --------------- socket() функция ------------------*/
    /*
        Socket() функция создает новый сокет.
        На вход получает 3 аргумента,
            a. AF_INET: доменный адрес сокета.
            b. SOCK_STREAM: тип сокета. Потоковый сокет, в котором сообщение
            читается последовательным потоком(TCP).
            c. Третий это аргумент протокола: всегда должен быть 0.
            Операционная система выберет самый подходящий протокол.
            Функция возвращает файл-дескриптор целое число - соединение, которое
       используется для всех ссылок на этот сокет. Если произошла ошибка
       соединения, то возвращается -1.
    */

    client = socket(AF_INET, SOCK_STREAM, 0);
    printf("CLIENT\n");

    if (client < 0)
    {
        printf("Error establishing socket...\n");
        exit(1);
    }

    printf("=> Socket client has been created...\n");

    /*=======================================================================*/
    /* ---------- ИНИЦИАЛИЗАЦИЯ serv_addr ---------------------------------- */
    /*=======================================================================*/
    /*
        Переменная serv_addr - это структура sockaddr_in.

        sin_family содержит код для адресной семьи. Всегда должна быть установлена
       AF_INET.

        htons() функция переводит номер порта из последовательности байтов
       компьютера в номер порта для работы с сетью.
    */

    server_addr.sin_family = AF_INET;
    server_addr.sin_port = htons(portNum);

    /*
            Эта функция возвращает 1, если IP-адрес действительный и 0, если
       недействительный.

        Функция inet_pton переводит IP-адрес в формат Internet.

        inet_ntoa переводит обратно из пакета в IP-адрес
    */

    inet_pton(AF_INET, ip,
        &server_addr.sin_addr); // convert IPv4 and IPv6 addresses from text to binary

    /*=======================================================================*/
    /* ---------- УСТАНОВКА СОЕДИНЕНИЯ С СЕРВЕРОМ ---------------------------*/
    /*=======================================================================*/
    /*
        Этот этап аналогичен этапу "Привязка сокета" (bind()) для сервера
        Для клиента bind() не нужен.
        Клиент обычно НЕ вызывает bind().
        Система сама автоматически делает bind() с произвольным свободным портом,
       когда ты вызываешь connect() или send().
    */

    /* ---------------- connect() ---------------- */
    /*
        Функция connect вызывается клиентом для установки соединения с сервером.
        Ей нужны 3 аргумента:
            a. файловый дескриптор сокета,
            b. адрес хоста, к которому клиент хочет подключится (включая номер
       порта), c. размер адреса.

        Функция возвращает 0 при успехе и 1 при неудаче.

        Примечание: клиенту нужно знать номер порта сервера, а не свой номер
       порта.
    */
    if (connect(client, (struct sockaddr*)&server_addr, sizeof(server_addr)) == 0)
        printf("=> Connection to the server %s with port number: %d\n",
            inet_ntoa(server_addr.sin_addr), portNum);

    if (connect(client, (struct sockaddr*)&server_addr, sizeof(server_addr)) == 0)
        printf("=> Connection to the server port number: %d \n", portNum);

    // Получение подтверждения от сервера
    printf("=> Awaiting confirmation from the server...\n");
    if (!receive_and_display_client(client, &isExit))
    {
        printf("=> Error receiving confirmation\n");
        close(client);
        return 1;
    }
    printf("=> Connection confirmed, you are good to go...\n");

    printf("\n\n=> Enter # to end the connection\n");

    /*=======================================================================*/
    /* ------------- ОСНОВНОЙ ЦИКЛ  ---------------------------------------- */
    /*=======================================================================*/
    /*
        После установки соединения клиент может отправлять сообщения первым.
        Каждое сообщение кодируется с помощью байт-стаффинга и обрамляется
        маркерами SOP/EOP. Ответы сервера принимаются и декодируются.
        Если приходит #, программа завершается.
    */

    do
    {
        /*===================================================================*/
        /* ---------------- СООБЩЕНИЕ КЛИЕНТА ------------------------------ */
        /*===================================================================*/
        printf("Client: ");
        if (!input_and_send_encoded_client(client, &isExit))
        {
            printf("=> Error sending message or connection closed\n");
            isExit = true;
            break;
        }

        /*===============================================================*/
        /* ---------------- ЧТЕНИЕ ОТВЕТА СЕРВЕРА ---------------------- */
        /*===============================================================*/
        /*
            Ожидаем ответ сервера и считываем его значение с декодированием.
            Если приходит #, завершаем программу.
        */
        printf("Server: ");
        if (!receive_and_display_client(client, &isExit))
        {
            printf("=> Error receiving message or connection closed\n");
            isExit = true;
            break;
        }

    } while (!isExit);

    /*===================================================================*/
    /* ---------------- ЗАВЕРШЕНИЕ СОЕДИНЕНИЯ -------------------------- */
    /*===================================================================*/
    /* ----------------- close() --------------- */

    /*
        Как только пользователь нажмет # для завершения соединения,
        цикл завершится и закроет сокет соединения.
    */

    printf("\n=> Connection terminated.\n\nGoodbye...\n");

    close(client);
    return 0;
}
