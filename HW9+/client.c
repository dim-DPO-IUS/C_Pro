 // Константы для байт-стаффинга
#define SOP 0x7E
#define EOP 0x7E
#define ESC 0x7D
#define XOR 0x20

/* Прототипы функций */
bool input_and_send_encoded_client(int client, bool* isExit);
bool receive_and_display_client(int client, bool* isExit);

/*=======================================================================*/
/* ---------- ВВОД И ОТПРАВКА ЗАКОДИРОВАННОГО СООБЩЕНИЯ -----------------*/
/*=======================================================================*/
/*
    Функция считывает сообщение клиента с клавиатуры и отправляет его серверу
    с использованием байт-стаффинга.

    Алгоритм работы:
    1. Считывает всё сообщение до перевода строки в буфер
    2. Проверяет, не является ли сообщение командой завершения (один символ '#')
    3. Отправляет маркер начала пакета (SOP = 0x7E)
    4. Отправляет каждый символ с кодированием:
       - если символ равен SOP (0x7E), заменяет на ESC (0x7D) и (SOP^XOR = 0x5E)
       - если символ равен ESC (0x7D), заменяет на ESC (0x7D) и (ESC^XOR = 0x5D)
       - остальные символы отправляет как есть
    5. В конце отправляет маркер конца пакета (EOP = 0x7E)

    Параметры:
        client  - дескриптор сокета клиента
        isExit  - указатель на флаг завершения (может быть изменен)

    Возвращает:
        true, если сообщение было успешно отправлено
        false, если произошла ошибка
*/
bool input_and_send_encoded_client(int client, bool* isExit)
{
    char c;
    char message[1024];  // Буфер для сообщения
    int msg_len = 0;     // Длина сообщения

    // Считываем всё сообщение до перевода строки в буфер
    do
    {
        c = getchar();
        if (msg_len < sizeof(message) - 1)
        {
            message[msg_len++] = c;
        }
    } while (c != '\n');
    message[msg_len] = '\0';  // Завершаем строку нулем

    // Проверяем, не является ли сообщение командой выхода
    // msg_len == 2 означает: символ '#' и символ '\n'
    if (msg_len == 2 && message[0] == '#')
    {
        *isExit = true;
    }

    // Отправляем маркер начала пакета
    c = SOP;
    if (send(client, &c, 1, 0) <= 0)
    {
        return false;
    }

    // Отправляем закодированное сообщение (без завершающего нуля)
    for (int i = 0; i < msg_len; i++)
    {
        c = message[i];

        // Проверяем, не является ли символ служебным
        if (c == SOP)
        {  // Встретили маркер - нужно экранировать
            c = ESC;      // Отправляем ESC
            if (send(client, &c, 1, 0) <= 0) return false;
            c = SOP ^ XOR; // Отправляем SOP XOR 0x20 = 0x5E
            if (send(client, &c, 1, 0) <= 0) return false;
        }
        else if (c == ESC)
        {  // Встретили escape-символ - тоже экранируем
            c = ESC;           // Отправляем ESC
            if (send(client, &c, 1, 0) <= 0) return false;
            c = ESC ^ XOR;     // Отправляем ESC XOR 0x20 = 0x5D
            if (send(client, &c, 1, 0) <= 0) return false;
        }
        else
        {
            // Обычный символ - отправляем как есть
            if (send(client, &c, 1, 0) <= 0)
            {
                return false;
            }
        }
    }

    // Отправляем маркер конца пакета
    c = EOP;
    if (send(client, &c, 1, 0) <= 0)
    {
        return false;
    }

    return true;
}

/*=======================================================================*/
/* ---------- ПРИЕМ И ДЕКОДИРОВАНИЕ ОТВЕТА ОТ СЕРВЕРА -------------------*/
/*=======================================================================*/
/*
    Функция принимает закодированный ответ от сервера и выводит его на экран.

    Алгоритм работы:
    1. Ожидает маркер начала пакета (SOP = 0x7E)
    2. Читает байты до маркера конца пакета (EOP = 0x7E), декодируя их:
       - если встречается ESC (0x7D), считывает следующий байт:
         * 0x5E -> восстанавливает SOP (0x7E)
         * 0x5D -> восстанавливает ESC (0x7D)
       - остальные байты сохраняются в буфер
    3. После получения EOP проверяет, не является ли сообщение командой завершения (один символ '#')

    Параметры:
        client  - дескриптор сокета клиента
        isExit  - указатель на флаг завершения (может быть изменен)

    Возвращает:
        true, если сообщение было успешно получено
        false, если произошла ошибка
*/
bool receive_and_display_client(int client, bool* isExit)
{
    char c;
    char received[1024];  // Буфер для принятого сообщения
    int recv_len = 0;     // Длина принятого сообщения

    // Ждем маркер начала пакета
    do
    {
        if (recv(client, &c, 1, 0) <= 0)
        {
            return false; // Ошибка приема или соединение закрыто
        }
    } while (c != SOP);

    // Читаем и декодируем данные до маркера конца
    while (1)
    {
        if (recv(client, &c, 1, 0) <= 0)
        {
            return false; // Ошибка приема
        }

        if (c == EOP)
        {
            break; // Дошли до конца пакета
        }

        if (c == ESC)
        {
            // Встретили escape-последовательность
            if (recv(client, &c, 1, 0) <= 0)
            {
                return false; // Ошибка приема
            }

            if (c == (SOP ^ XOR))
            {
                c = SOP; // Восстанавливаем SOP
            }
            else if (c == (ESC ^ XOR))
            {
                c = ESC; // Восстанавливаем ESC
            }
            else
            {
                // Неизвестная последовательность - сохраняем ESC как есть
                if (recv_len < sizeof(received) - 1)
                {
                    received[recv_len++] = ESC;
                }
                continue;
            }
        }

        // Сохраняем декодированный символ в буфер
        if (recv_len < sizeof(received) - 1)
        {
            received[recv_len++] = c;
        }
    }

    // Добавляем завершающий ноль
    received[recv_len] = '\0';

    // Выводим сообщение
    printf("%s", received);

    // Проверяем, не является ли сообщение командой выхода (один символ '#')
    if (recv_len == 1 && received[0] == '#')
    {
        *isExit = true;
    }

    printf("\n"); // Переводим строку после ответа сервера
    return true;
}



